package com.skillbridge.util;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertTrue;

abstract class JdbcTestSupport {
    @BeforeEach
    void startDatabase() throws SQLException {
        HikariConfig config = new HikariConfig();
        config.setJdbcUrl("jdbc:h2:mem:onestop_" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        config.setUsername("sa");
        config.setPassword("");
        config.setMaximumPoolSize(2);
        DBConnectionUtil.setTestDataSource(new HikariDataSource(config));
        createSchema();
    }

    @AfterEach
    void stopDatabase() {
        DBConnectionUtil.shutdown();
    }

    protected void execute(String sql) throws SQLException {
        try (Connection connection = DBConnectionUtil.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    protected String stringValue(String sql, String parameter) throws SQLException {
        try (Connection connection = DBConnectionUtil.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, parameter);
            try (ResultSet rs = statement.executeQuery()) {
                assertTrue(rs.next());
                return rs.getString(1);
            }
        }
    }

    protected int intValue(String sql, String parameter) throws SQLException {
        try (Connection connection = DBConnectionUtil.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, parameter);
            try (ResultSet rs = statement.executeQuery()) {
                assertTrue(rs.next());
                return rs.getInt(1);
            }
        }
    }

    private void createSchema() throws SQLException {
        execute("CREATE TABLE users (id VARCHAR(64) PRIMARY KEY, email VARCHAR(191) UNIQUE, "
                + "password_hash VARCHAR(255) NOT NULL, role VARCHAR(16) NOT NULL, full_name VARCHAR(120), "
                + "phone VARCHAR(32), status VARCHAR(16) DEFAULT 'ACTIVE', "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        execute("CREATE TABLE customer_profiles (id VARCHAR(64) PRIMARY KEY, user_id VARCHAR(64), city VARCHAR(64))");
        execute("CREATE TABLE service_categories (id VARCHAR(64) PRIMARY KEY, code VARCHAR(32), "
                + "name_en VARCHAR(100), description VARCHAR(1000))");
        execute("CREATE TABLE provider_profiles (id VARCHAR(64) PRIMARY KEY, user_id VARCHAR(64), "
                + "business_name VARCHAR(160), bio VARCHAR(2000), years_experience INT, "
                + "rating_avg DECIMAL(3,2), review_count INT, completed_jobs_count INT, is_verified BOOLEAN, "
                + "emergency_available BOOLEAN, base_hourly_rate DECIMAL(10,2), profile_image_url VARCHAR(500), "
                + "city VARCHAR(64))");
        execute("CREATE TABLE provider_services (id VARCHAR(64) PRIMARY KEY, provider_id VARCHAR(64), "
                + "category_id VARCHAR(64), service_title VARCHAR(150), description VARCHAR(1000), "
                + "price_type VARCHAR(16), price DECIMAL(10,2), is_active BOOLEAN)");
        execute("CREATE TABLE bookings (id VARCHAR(64) PRIMARY KEY, booking_reference VARCHAR(32), "
                + "customer_id VARCHAR(64), provider_id VARCHAR(64), service_id VARCHAR(64), "
                + "service_title VARCHAR(150), category_id VARCHAR(64), problem_description VARCHAR(10000), "
                + "service_address VARCHAR(255), city VARCHAR(64), scheduled_date DATE, "
                + "scheduled_time_slot VARCHAR(64), status VARCHAR(32), is_emergency BOOLEAN, "
                + "estimated_total DECIMAL(10,2), final_total DECIMAL(10,2), "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        execute("CREATE TABLE booking_status_history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "booking_id VARCHAR(64), from_status VARCHAR(32), to_status VARCHAR(32), "
                + "change_reason VARCHAR(255), changed_by_user_id VARCHAR(64), "
                + "changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        execute("CREATE TABLE notifications (id VARCHAR(64) PRIMARY KEY, user_id VARCHAR(64), "
                + "title VARCHAR(150), message VARCHAR(1000), type VARCHAR(32), related_booking_id VARCHAR(64))");
        execute("CREATE TABLE service_attachments (id VARCHAR(64) PRIMARY KEY, booking_id VARCHAR(64), "
                + "file_name VARCHAR(255), file_url VARCHAR(500), content_type VARCHAR(100), file_data BLOB, "
                + "file_size_bytes BIGINT, uploaded_by_user_id VARCHAR(64))");
        execute("CREATE TABLE invoices (id VARCHAR(64) PRIMARY KEY, invoice_number VARCHAR(64), "
                + "booking_id VARCHAR(64), customer_id VARCHAR(64), provider_id VARCHAR(64), "
                + "subtotal DECIMAL(10,2), tax_amount DECIMAL(10,2), discount_amount DECIMAL(10,2), "
                + "total_amount DECIMAL(10,2), payment_status VARCHAR(16), payment_method VARCHAR(50), "
                + "issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        execute("CREATE TABLE invoice_items (id VARCHAR(64) PRIMARY KEY, invoice_id VARCHAR(64), "
                + "item_description VARCHAR(255), quantity INT, unit_price DECIMAL(10,2), total_price DECIMAL(10,2))");
        execute("CREATE TABLE quotations (id VARCHAR(64) PRIMARY KEY, booking_id VARCHAR(64), provider_id VARCHAR(64), "
                + "labor_cost DECIMAL(10,2), material_cost DECIMAL(10,2), additional_charges DECIMAL(10,2), "
                + "total_quoted_amount DECIMAL(10,2), estimated_duration_hours DECIMAL(4,1), "
                + "validity_until DATE, notes_exclusions VARCHAR(1000), status VARCHAR(16), "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
    }
}
